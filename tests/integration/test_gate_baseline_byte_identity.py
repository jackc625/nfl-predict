def _committed_baseline_block() -> str:
    """Return the committed ``[baseline.*]`` section of config/gate.toml, verbatim.

    Located by CONTENT: the generator's own header line is found, the block starts on the
    separator line immediately above it, and it runs to the last non-blank line of the
    file. Reading the file in text mode folds CRLF to LF, so the comparison is unaffected
    by this repository's ``core.autocrlf=true`` working-tree line endings.
    """
    lines = _GATE_TOML.read_text(encoding="utf-8").split("\n")

    try:
        header = lines.index(_BLOCK_HEADER_LINE)
    except (
        ValueError
    ) as error:  # pragma: no cover - a broken checkout, not a runtime case
        msg = (
            f"config/gate.toml no longer contains the generator's header line "
            f"{_BLOCK_HEADER_LINE!r}, so the committed baseline block cannot be located. "
            "The block must be written by pasting scripts/freeze_gate_baseline.py's output "
            "whole, header included."
        )
        raise AssertionError(msg) from error

    start = header - 1
    last = max(index for index, line in enumerate(lines) if line.strip())

    trailing = [line for line in lines[last + 1 :] if line.strip()]
    assert not trailing, (
        "config/gate.toml carries non-blank content after the [baseline.*] block "
        f"({trailing!r}). The extraction assumes the generated block ends the file; move "
        "the new content above the block or teach this helper where the block ends."
    )

    return "\n".join(lines[start : last + 1]) + "\n"


