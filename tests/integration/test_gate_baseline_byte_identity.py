class TestTheRegeneratedBaselineIsByteIdenticalToTheCommittedOne:
    """The independent second proof that 2021-2024 gold did not move."""

    @pytest.mark.integration
    def test_the_generated_block_equals_the_committed_block_byte_for_byte(self) -> None:
        _require_rescore_inputs()
        from scripts.freeze_gate_baseline import compute_baseline, render_baseline_toml

        generated = render_baseline_toml(
            compute_baseline(artifacts_dir=REPO_ROOT / "artifacts")
        )
        committed = _committed_baseline_block()

        if generated != committed:
            generated_lines = generated.split("\n")
            committed_lines = committed.split("\n")
            first = next(
                (
                    index
                    for index in range(max(len(generated_lines), len(committed_lines)))
                    if generated_lines[index : index + 1]
                    != committed_lines[index : index + 1]
                ),
                0,
            )
            msg = (
                "the REGENERATED gate baseline block is not byte-identical to the block "
                "committed in config/gate.toml. This is the INDEPENDENT second proof that "
                "the 2021-2024 gold slice did not move, arriving through the gate's own "
                "scoring loaders rather than through the fingerprint -- so a difference IS "
                "the gold-moved signal and STOPS the phase. Do NOT re-freeze the baseline "
                "to make this pass: re-freezing would erase the evidence that gold moved. "
                f"First differing line ({first}): committed "
                f"{committed_lines[first : first + 1]!r} vs generated "
                f"{generated_lines[first : first + 1]!r}."
            )
            raise AssertionError(msg)

    @pytest.mark.integration
    def test_the_frozen_baseline_extraction_is_not_vacuous(self) -> None:
        """A comparison against an empty or partial block would pass for free.

        RETARGETED by Plan 33.1-09 Task 3 to ``_FROZEN_BASELINE``. It read the live holdout
        before, which was the same four seasons and is no longer: the [baseline.*] block's
        per-season tables are 2021-2024 by definition -- that is the window it was frozen
        over -- and asking whether it carries a table for the LIVE partition's seasons would
        be asking a question about the wrong object.
        """
        committed = _committed_baseline_block()

        for target in ("wp", "ats", "ou"):
            assert f"[baseline.{target}.pooled]" in committed, (
                f"the extracted committed block carries no [baseline.{target}.pooled] "
                "table, so the byte-identity comparison is judging a fragment."
            )
            for season in _FROZEN_BASELINE:
                assert f"[baseline.{target}.season.{season}]" in committed, (
                    f"the extracted committed block carries no "
                    f"[baseline.{target}.season.{season}] table."
                )
        assert _BLOCK_HEADER_LINE in committed
        assert committed.endswith("\n")


class TestTheWidenedOddsTableDoesNotPerturbTheBaseline:
    """LANDMINE-5, second ordering constraint: the four new juice columns are inert here.

    The generator re-scores through the closing-odds loader, which now sees four columns it
    did not see when the baseline was frozen. Proving they change nothing is what makes a
    byte-identity FAILURE unambiguous: it could then only mean gold moved.
    """

    @pytest.mark.integration
    def test_dropping_the_juice_columns_changes_no_frozen_baseline_per_season_figure(
        self,
    ) -> None:
        """RETARGETED by Plan 33.1-09 Task 3 to the FROZEN baseline's own seasons.

        This control exists to make a byte-identity FAILURE unambiguous, and byte-identity is
        a property of the [baseline.*] block -- a historical record frozen over 2021-2024. It
        used to slice the live holdout constant, which was the same four seasons. It is not
        any more, so it slices ``_FROZEN_BASELINE``. It would have kept PASSING either way
        (both sides of the comparison use one window), which is exactly why the retarget is
        worth making deliberately: a green test measuring the wrong population is the
        hardest kind to notice.
        """
        _require_rescore_inputs()
        if not _SILVER_ODDS.is_file():
            pytest.skip(
                "the widened odds table is not present at "
                "data/silver/odds_snapshot.parquet, so the juice-column perturbation "
                "control cannot run."
            )

        from backtest.diagnose import score_deployed_artifacts
        from backtest.engine import BacktestEngine
        from models.clv import compute_clv_for_predictions
        from models.deploy_gate import per_season_clv

        engine = BacktestEngine()
        odds = engine._load_closing_odds()

        juice = [column for column in _juice_columns() if column in odds.columns]
        if len(juice) != len(_juice_columns()):
            pytest.skip(
                "the four juice columns are absent from the loaded odds frame, so the "
                "perturbation control would compare a frame with itself and prove nothing."
            )

        narrowed = odds.drop(columns=juice)
        compared = 0
        for target in ("wp", "ats", "ou"):
            features = engine._load_features(target)
            in_frozen = (features["season"] >= _FROZEN_BASELINE[0]) & (
                features["season"] <= _FROZEN_BASELINE[-1]
            )
            gold_df: pd.DataFrame = features.loc[in_frozen].copy()

            # Score ONCE and reuse. The claim under test is about the ODDS frame, so
            # re-scoring per variant would introduce a second difference and weaken it.
            scored = score_deployed_artifacts(
                target, gold_df=gold_df, artifacts_dir=REPO_ROOT / "artifacts"
            )

            wide = compute_clv_for_predictions(scored, odds, target)
            thin = compute_clv_for_predictions(scored, narrowed, target)
            wide_valid = wide.loc[wide["has_closing_odds"]]
            thin_valid = thin.loc[thin["has_closing_odds"]]

            assert len(wide_valid) == len(thin_valid), (
                f"{target}: the widened odds frame admits {len(wide_valid)} scored rows "
                f"against {len(thin_valid)} for the narrowed one. The four juice columns "
                "changed the JOIN, not merely the frame's width."
            )

            wide_seasons = per_season_clv(wide_valid, target, seasons=_FROZEN_BASELINE)
            thin_seasons = per_season_clv(thin_valid, target, seasons=_FROZEN_BASELINE)
            assert set(wide_seasons) == set(thin_seasons)

            for season in sorted(wide_seasons):
                for key in ("n", "mean", "t", "p"):
                    assert wide_seasons[season][key] == thin_seasons[season][key], (
                        f"{target} season {season}: '{key}' is "
                        f"{wide_seasons[season][key]} with the four juice columns present "
                        f"and {thin_seasons[season][key]} without them. The added columns "
                        "perturb the per-season closing-line-value computation, so a "
                        "byte-identity failure could no longer be read as a gold move."
                    )
                    compared += 1

        # Guard the guard: a loop that silently compared nothing would pass for free.
        expected = 3 * len(_FROZEN_BASELINE) * 4
        assert compared == expected, (
            f"the perturbation control compared {compared} per-season figures, not the "
            f"{expected} expected (3 targets x {len(_FROZEN_BASELINE)} frozen seasons x 4 "
            "keys)."
        )


